package ca.bcit.comp2522.lab6;

/**
 * An abstract class representing a piece of literature.
 * This class defines a basic structure for any literary item
 * by requiring a title through the getTitle method.
 *
 * @author Linh Hoang
 * @author Pouyan Norouzi
 */
public abstract class Literature
{

   /**
    * Retrieves the title of the literature item.
    *
    * @return The title of the literature item.
    */
   public abstract String getTitle();
}
